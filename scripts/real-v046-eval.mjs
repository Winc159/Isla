import { spawn } from 'node:child_process';
import { createInterface } from 'node:readline';
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

const root = process.cwd();
const config = JSON.parse(await readFile(join(process.env.USERPROFILE, '.isla', 'config.json'), 'utf8'));
const profile = config.profiles?.bailian;
if (!profile) throw new Error('Bailian Profile 不存在');
const outputDir = join(root, '.isla-local', 'evaluations');
await mkdir(outputDir, { recursive: true });
const transcriptPath = join(outputDir, `v046-real-eval-${new Date().toISOString().replaceAll(/[:.]/g, '-')}.md`);
const sessionDir = join(outputDir, `.v046-session-${Date.now()}`);
const workspace = join(outputDir, `.v046-workspace-${Date.now()}`);
await mkdir(sessionDir, { recursive: true });
await mkdir(workspace, { recursive: true });
const child = spawn(process.execPath, [join(root, 'dist', 'cli.js'), '--env', '--protocol', 'ndjson'], { cwd: workspace, env: { ...process.env, ISLA_PROVIDER: 'bailian', ISLA_MODEL: profile.model, DASHSCOPE_API_KEY: profile.apiKey, ISLA_BASE_URL: profile.baseURL, ISLA_SESSION_DIR: sessionDir, ISLA_MEMORY_ENABLED: '0' }, stdio: ['pipe', 'pipe', 'pipe'] });
const events = [];
const errors = [];
createInterface({ input: child.stdout }).on('line', line => { try { events.push(JSON.parse(line)); } catch { errors.push('non-ndjson'); } });
child.stderr.on('data', chunk => errors.push(String(chunk).replaceAll(/api[_-]?key|authorization/gi, '[redacted]')));
const wait = async predicate => { const deadline = Date.now() + 120_000; while (Date.now() < deadline) { const found = events.find(predicate); if (found) return found; await new Promise(resolve => setTimeout(resolve, 25)); } throw new Error(`timeout: ${events.map(event => event.type).join(',')}`); };
const send = request => child.stdin.write(`${JSON.stringify(request)}\n`);
await wait(event => event.type === 'ready');
const start = Date.now();
send({ type: 'prompt', id: 'short', text: '请只回答 ready。' });
const short = await wait(event => event.type === 'response_end' && event.id === 'short');
const huge = `${'这是上下文预算专项测试文本。'.repeat(20_000)}\n请只回答 rejected。`;
send({ type: 'prompt', id: 'oversized', text: huge });
const oversized = await wait(event => (event.type === 'error' || event.type === 'response_end') && event.id === 'oversized');
send({ type: 'exit', id: 'exit' });
await wait(event => event.type === 'bye' && event.id === 'exit');
await writeFile(transcriptPath, `# v0.4.6 百炼真实评估\n\n- Model：${profile.model}\n- 短请求耗时：${short.elapsedMs ?? 'unknown'} ms\n- 超大单轮耗时：${Date.now() - start} ms\n- 超大单轮终态：${JSON.stringify({ type: oversized.type, code: oversized.code, message: oversized.message })}\n- 进程 stderr 条目：${errors.length}\n\n结论：${oversized.type === 'error' && oversized.code === 'CONTEXT_INPUT_TOO_LARGE' ? '单轮上下文在 Provider 调用前被本地拒绝。' : '未得到预期的本地上下文门禁结果。'}\n`, 'utf8');
if (child.exitCode === null) child.kill();
console.log(JSON.stringify({ model: profile.model, shortElapsedMs: short.elapsedMs, oversized: { type: oversized.type, code: oversized.code }, transcriptPath }));
